let updatedCount = 0;
for (const [file, meta] of Object.entries(seoDefinitions)) {
  const filePath = path.join(root, file);
  let html;
  try {
    html = await readFile(filePath, "utf8");
  } catch {
    continue;
  }

  // <title> の置換
  html = html.replace(/<title>[^<]+<\/title>/i, `<title>${meta.title}</title>`);

  // <meta name="description"> の置換
  html = html.replace(/<meta\s+name="description"\s+content="[^"]*"/i, `<meta name="description" content="${meta.desc}"`);

  await writeFile(filePath, html, "utf8");
  updatedCount++;
}

console.log(`SEOメタ（title / description）を ${updatedCount} ページ更新しました`);
